SELECT
    m.id             AS impact_id,
    m.news_id,
    COALESCE(m.llm_model, n.llm_model) AS llm_model,
    n.source,
    n.title,
    n.timestamp_utc  AS news_published_at,
    m.ticker,
    m.symbol,
    m.t0_timestamp,
    m.p0_price,
    m.pre_drift_pct,
    m.volume_surge_ratio,
    m.return_15m_pct,
    m.return_1h_pct,
    m.return_2h_pct,
    m.return_4h_pct,
    m.return_8h_pct,
    m.return_24h_pct,
    m.max_runup_pct,
    m.max_drawdown_pct,
    m.volatility_range_pct,
    m.sentiment_label,
    m.sentiment_score,
    m.impact_magnitude,
    m.target_horizon_hours,
    m.is_mean_reverting_expected,
    m.is_speculative,
    m.is_impulse_confirmed,
    m.is_target_horizon_aligned,
    m.is_aligned_15m,
    m.is_aligned_1h,
    m.is_aligned_4h,
    m.is_aligned_24h,
    m.evaluated_at
FROM news_market_impact m
JOIN raw_news n ON n.id = m.news_id
ORDER BY m.t0_timestamp ASC;
